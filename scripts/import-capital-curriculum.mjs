// Deterministic SQL generation only: never connects to a remote database.
import { readFile, writeFile, readdir } from "node:fs/promises";
import { createHash } from "node:crypto";
const path = "data/curriculum/capital-computing-2021.json";
const data = JSON.parse(await readFile(path, "utf8"));
const { source, courses } = data;
if (
  createHash("sha256")
    .update(await readFile(source.file))
    .digest("hex") !== source.sha256
)
  throw Error("Source PDF hash mismatch");
const seen = new Set();
for (const c of courses) {
  if (
    seen.has(c.code) ||
    !/^(CS|IS|IT|AI|MA|ST|PH|HU) [1-4][0-9]{2}$/.test(c.code) ||
    c.year !== Number(c.code.split(" ")[1][0]) ||
    !c.title_ar ||
    !c.title_en ||
    !c.requirements.length
  )
    throw Error("Invalid course " + c.code);
  seen.add(c.code);
}
const quote = (s) => "'" + String(s).replaceAll("'", "''") + "'";
const groups = {
  CS: ["Computer Science", "علوم الحاسب"],
  IS: ["Information Systems", "نظم المعلومات"],
  IT: ["Information Technology", "تكنولوجيا المعلومات"],
  AI: ["Artificial Intelligence", "الذكاء الاصطناعي"],
  MA: ["Mathematics", "رياضيات"],
  ST: ["Statistics", "إحصاء"],
  PH: ["Physics", "فيزياء"],
  HU: ["Humanities", "علوم إنسانية"],
};
let sql = `-- Generated by node scripts/import-capital-curriculum.mjs from ${path}.\n-- Source SHA-256: ${source.sha256}\n-- 2021 regulations supplied by the owner for Capital University.\n-- Article 18: first numeric digit is level; no semester inferred.\n-- Existing universities, courses, content and follows are preserved.\ndo $$\ndeclare u uuid; f uuid; c uuid;\nbegin\n select id into strict u from public.universities where slug=${quote(source.university_slug)};\n select id into strict f from public.faculties where slug=${quote(source.faculty_slug)};\n if not exists(select 1 from public.university_faculties where university_id=u and faculty_id=f) then raise exception 'faculty not configured';end if;\n`;
for (const c of courses) {
  const [dept, ar] = groups[c.code.split(" ")[0]];
  sql += `\n -- ${c.code}; printed page(s) ${[...new Set(c.requirements.map((r) => r.page))].join(", ")}.\n insert into public.courses(university_id,faculty_id,slug,code,code_ar,title,title_ar,title_en,department,department_ar,year_level,credit_hours,prerequisite_note,curriculum_source)\n values(u,f,${quote("capital-" + c.code.toLowerCase().replace(" ", "-"))},${quote(c.code)},${quote(c.code_ar)},${quote(c.title_ar)},${quote(c.title_ar)},${quote(c.title_en)},${quote(dept)},${quote(ar)},${c.year},${c.credit_hours},${quote(c.prerequisites)},'capital-computing-2021')\n on conflict(university_id,department,code) do update set faculty_id=excluded.faculty_id,title=excluded.title,title_ar=excluded.title_ar,title_en=excluded.title_en,code_ar=excluded.code_ar,department_ar=excluded.department_ar,year_level=excluded.year_level,credit_hours=excluded.credit_hours,prerequisite_note=excluded.prerequisite_note,curriculum_source=excluded.curriculum_source\n returning id into c;\n`;
  for (const r of c.requirements)
    sql += ` insert into public.course_requirements(course_id,scope,kind,source_page) values(c,${quote(r.scope)},${quote(r.kind)},${r.page}) on conflict(course_id,scope) do update set kind=excluded.kind,source_page=excluded.source_page;\n`;
}
sql += "end;$$;\n";
const migration = (await readdir("supabase/migrations")).find((n) =>
  n.endsWith("_capital_computing_curriculum.sql"),
);
const out = "supabase/migrations/" + migration;
if (process.argv.includes("--check")) {
  if ((await readFile(out, "utf8")) !== sql)
    throw Error("Curriculum migration is out of date");
  console.log(
    `Verified ${courses.length} courses and ${courses.flatMap((c) => c.requirements).length} requirement mappings against generated SQL and source PDF hash.`,
  );
} else {
  await writeFile(out, sql);
  console.log("Generated " + out);
}
